import { useTheme } from 'next-themes'
import { useEffect, useMemo, useRef, useState } from 'react'
import { hydrate, renderSVG } from '../.claude/skills/chartkit/chartkit.mjs'
import Link from './Link'

interface Props {
  /** Raw chartkit spec JSON (from the `foo.chart.json` sidecar) */
  spec: string
  /** Pre-rendered light SVG, used for the full-size link */
  src: string
  /** Pre-rendered dark SVG, if there is one */
  darkSrc?: string | null
  alt?: string
}

// Matches the content column (max-w-3xl); hydrate() re-lays out to the real width on the client
const SSR_WIDTH = 768

/**
 * Deterministic per chart so server and client render identical ids:
 * `/images/2026/Foo Bar-dark.svg` → `ck-foo-bar`.
 */
const idPrefixFor = (src: string) => {
  const stem = (src.split('/').pop() ?? '').replace(/\.[^.]+$/, '').replace(/-(light|dark)$/, '')
  const slug = stem
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
  return `ck-${slug || 'chart'}`
}

/**
 * A chartkit chart drawn live: server-rendered as inline SVG (so it follows `html.dark` and
 * works without JavaScript), then hydrated on the client for resizing, hover and legend toggles.
 */
export default function Chart({ spec, src, darkSrc, alt }: Props) {
  const containerRef = useRef<HTMLDivElement>(null)
  const parsed = useMemo(() => JSON.parse(spec), [spec])
  const idPrefix = idPrefixFor(src)
  const svg = useMemo(
    () => renderSVG(parsed, { theme: 'auto', width: SSR_WIDTH, idPrefix }),
    [parsed, idPrefix]
  )

  useEffect(() => {
    const element = containerRef.current?.querySelector('svg')
    if (!element) return
    return hydrate(element, parsed, { theme: 'auto', idPrefix })
  }, [parsed, idPrefix])

  // resolvedTheme is unknown during SSR, so link to the light image until mounted
  const { resolvedTheme } = useTheme()
  const [mounted, setMounted] = useState(false)
  useEffect(() => setMounted(true), [])
  const fullSizeHref = mounted && resolvedTheme === 'dark' && darkSrc ? darkSrc : src

  return (
    // No role="img" on the SVG wrapper: that would hide the interactive legend from assistive tech
    <figure className="not-prose my-8" aria-label={alt || undefined}>
      <div
        ref={containerRef}
        // biome-ignore lint/security/noDangerouslySetInnerHtml: SVG is generated by chartkit from our own spec
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <div className="mt-2 text-right">
        <Link
          href={fullSizeHref}
          className="text-sm text-gray-500 hover:text-primary-500 dark:text-gray-400 dark:hover:text-primary-400"
        >
          Open full size ↗
        </Link>
      </div>
    </figure>
  )
}
